// Writes src/generated/files.ts: the CLI, its installer, the agent skill and the dashboard's assets (cloud/assets:
// styles, script, fonts, icons), so the server can serve them on either platform. Wrangler runs this before every
// build (see "build" in wrangler.jsonc).
import { buildSync } from "esbuild";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const cloud = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(cloud, "..");
const read = (path) => readFileSync(join(repo, path), "utf8");

/** Every file of the agent skill, by its path inside the skill, so a new reference is served without a change here. */
function skillFiles(dir = join(repo, "skills", "usual-base"), root = dir, files = {}) {
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.name.startsWith(".")) continue;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) skillFiles(path, root, files);
    else files[relative(root, path)] = readFileSync(path, "utf8");
  }
  return files;
}

// The CLI's source is split into modules; people download it as the one file this bundles.
const [cli] = buildSync({
  entryPoints: [join(repo, "cli", "usual-base.mjs")],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node18",
  write: false,
  logLevel: "error",
  banner: { js: "// The Usual Base CLI, bundled from cli/ in https://github.com/usual-labs/usual-base. `usual-base help` lists its commands." },
}).outputFiles;

// The dashboard's assets, served at /assets/<name>.<hash>.<ext> so they can be cached for good. app.css refers to
// the fonts by name (url("fonts/Figtree-latin.woff2")); those references become the hashed paths.
const TYPES = { ".css": "text/css; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".woff2": "font/woff2",
  ".ttf": "font/ttf", ".png": "image/png" };
const assetsDir = join(cloud, "assets");
const assetFiles = (dir = assetsDir, found = []) => {
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) assetFiles(path, found);
    else if (TYPES[extname(entry.name)]) found.push(relative(assetsDir, path));
  }
  return found;
};
const assetPath = {};
const assets = {};
const addAsset = (name, bytes) => {
  const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 10);
  const ext = extname(name);
  const path = `/assets/${name.slice(0, -ext.length)}.${hash}${ext}`;
  assetPath[name] = path;
  assets[path] = { type: TYPES[ext], body: Buffer.from(bytes).toString("base64") };
};
const textAssets = [".css", ".js"];
const names = assetFiles();
for (const name of names.filter((n) => !textAssets.includes(extname(n)))) addAsset(name, readFileSync(join(assetsDir, name)));
for (const name of names.filter((n) => textAssets.includes(extname(n)))) {
  const text = readFileSync(join(assetsDir, name), "utf8").replace(/url\("([^"]+)"\)/g, (match, ref) =>
    assetPath[ref] ? `url("${assetPath[ref]}")` : match);
  addAsset(name, Buffer.from(text));
}

const files = {
  cli: cli.text,
  installScript: read("cloud/src/install.sh"),
  skill: skillFiles(),
  assetPath,
  assets,
};

const out = join(cloud, "src", "generated", "files.ts");
const text =
  "// Generated by scripts/embed.mjs from the repository's cli/, cloud/src/install.sh, skills/ and cloud/assets/. Don't edit.\n" +
  Object.entries(files).map(([name, value]) => `export const ${name} = ${JSON.stringify(value)};\n`).join("");
// Only a real change is written, so the build's own output doesn't set off another build.
if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
}
