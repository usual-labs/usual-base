// Writes src/generated/files.ts: the CLI, its installer and the agent skill as strings, so the Worker can
// serve them. Wrangler runs this before every build (see "build" in wrangler.jsonc).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const cloud = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(cloud, "..");
const read = (path) => readFileSync(join(repo, path), "utf8");

const files = {
  cli: read("cli/usual-base.mjs"),
  installScript: read("cloud/src/install.sh"),
  skill: {
    "SKILL.md": read("skills/usual-base/SKILL.md"),
    "references/markdown.md": read("skills/usual-base/references/markdown.md"),
    "references/sync.md": read("skills/usual-base/references/sync.md"),
  },
};

const out = join(cloud, "src", "generated", "files.ts");
const text =
  "// Generated by scripts/embed.mjs from the repository's cli/, cloud/src/install.sh and skills/. Don't edit.\n" +
  Object.entries(files).map(([name, value]) => `export const ${name} = ${JSON.stringify(value)};\n`).join("");
// Only a real change is written, so the build's own output doesn't set off another build.
if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
}
